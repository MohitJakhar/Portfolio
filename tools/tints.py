"""Pick a folder colour for each project from its poster.

    python tools/tints.py

Reads public/media/poster/<slug>.jpg and writes src/data/tints.ts. The colour
is the poster's most prominent *vivid* hue (weighted by saturation and
brightness), so a mostly white or black poster still takes the colour of its
logo or subject rather than going grey. A poster with no vivid colour at all
falls back to a neutral cool grey. Needs Pillow.
"""
import colorsys
import pathlib
import re

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
POSTERS = ROOT / "public" / "media" / "poster"
PROJECTS = ROOT / "src" / "data" / "projects.ts"
OUT = ROOT / "src" / "data" / "tints.ts"

BINS = 24
FALLBACK = "#8a96a3"


def tint(path: pathlib.Path) -> str:
    raw = Image.open(path).convert("RGB").resize((72, 72)).tobytes()
    weight = [0.0] * BINS
    acc = [[0.0, 0.0, 0.0] for _ in range(BINS)]
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if s < 0.3 or v < 0.25:
            continue
        w = s * v
        k = int(h * BINS) % BINS
        weight[k] += w
        acc[k][0] += r * w
        acc[k][1] += g * w
        acc[k][2] += b * w
    best = max(range(BINS), key=lambda k: weight[k])
    # Low enough that a small vivid logo on a white poster still counts.
    if weight[best] < 4:
        return FALLBACK
    r, g, b = (c / weight[best] for c in acc[best])
    # Settle it into a range that reads as tinted glass on the paper: clearly
    # coloured, never neon, never muddy.
    h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
    s = min(max(s, 0.45), 0.8)
    v = min(max(v, 0.6), 0.88)
    r, g, b = colorsys.hsv_to_rgb(h, s, v)
    return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))


slugs = re.findall(r"slug: '([^']+)'", PROJECTS.read_text(encoding="utf-8"))
lines = [
    "// Generated by tools/tints.py from each project's poster. Re-run it when a",
    "// poster changes rather than editing by hand.",
    "export const TINTS: Record<string, string> = {",
]
for slug in slugs:
    c = tint(POSTERS / f"{slug}.jpg")
    lines.append(f"  '{slug}': '{c}',")
    print(slug, c)
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
