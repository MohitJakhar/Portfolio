"""List every video in each project's shared Drive folder.

    python tools/drive.py

Reads the `driveFolderId` of each project in src/data/projects.ts, lists the
public folder, and writes src/data/drive.ts: the Drive file id and name of
every video in it, plus its aspect ratio (read from Drive's thumbnail). The
project pages play these in Drive's own player, so the full-length films never
have to live in this repo. Re-run it after adding or renaming videos in Drive.
Folders must be shared as "Anyone with the link". Needs Pillow.
"""
import html
import io
import pathlib
import re
import urllib.request

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROJECTS = ROOT / "src" / "data" / "projects.ts"
OUT = ROOT / "src" / "data" / "drive.ts"

VIDEO = re.compile(r"\.(mp4|mov|webm|m4v|mkv)$", re.I)
ENTRY = re.compile(
    r'href="https://drive\.google\.com/file/d/([\w-]+)/view[^"]*".*?flip-entry-title">([^<]+)<',
    re.S,
)

def aspect(file_id: str) -> float:
    """Width / height of the video, from its Drive thumbnail; 16:9 if none."""
    try:
        url = f"https://drive.google.com/thumbnail?id={file_id}&sz=w320"
        img = Image.open(io.BytesIO(urllib.request.urlopen(url, timeout=30).read()))
        return round(img.width / img.height, 4)
    except Exception:
        return round(16 / 9, 4)


src = PROJECTS.read_text(encoding="utf-8")
projects = re.findall(r"slug: '([^']+)'.*?driveFolderId: '([^']+)'", src, re.S)

lines = [
    "// Generated by tools/drive.py from each project's shared Drive folder.",
    "// Re-run it after adding or renaming videos in Drive.",
    "export type DriveVideo = { id: string; name: string; aspect: number };",
    "",
    "export const DRIVE: Record<string, DriveVideo[]> = {",
]
for slug, folder in projects:
    url = f"https://drive.google.com/embeddedfolderview?id={folder}"
    page = urllib.request.urlopen(url, timeout=30).read().decode("utf-8", "replace")
    videos = [(i, html.unescape(n)) for i, n in ENTRY.findall(page) if VIDEO.search(html.unescape(n))]
    print(slug, len(videos))
    lines.append(f"  '{slug}': [")
    for vid, name in videos:
        lines.append(f"    {{ id: '{vid}', name: {name!r}, aspect: {aspect(vid)} }},")
    lines.append("  ],")
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
